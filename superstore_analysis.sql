-- Q1: SALES AND PROFIT BY SHIPPING MODE
SELECT
	SHIP_MODE,
	ROUND(SUM(SALES), 2) AS TOTAL_SALES,
	ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
	COUNT(*) AS TOTAL_ORDERS
FROM
	SUPERSTORE
GROUP BY
	SHIP_MODE
ORDER BY
	TOTAL_SALES DESC;

-- Q2: TOP 10 MOST PROFITABLE CUSTOMERS
SELECT
	CUSTOMER_NAME,
	ROUND(SUM(SALES), 2) AS TOTAL_SALES,
	ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
	COUNT(*) AS ORDER_COUNT,
	RANK() OVER (
		ORDER BY
			SUM(PROFIT) DESC
	) AS CUSTOMER_RANK
FROM
	SUPERSTORE
GROUP BY
	CUSTOMER_NAME
ORDER BY
	TOTAL_PROFIT DESC
LIMIT
	10;

-- Q3: SALES AND PROFIT BY CATEGORY AND SUB-CATEGORY
-- Business Question: Which products are driving revenue vs profit?
SELECT
	CATEGORY,
	SUB_CATEGORY,
	ROUND(SUM(SALES), 2) AS TOTAL_SALES,
	ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
	ROUND(SUM(PROFIT) * 100.0 / SUM(SALES), 2) AS PROFIT_MARGIN_PCT
FROM
	SUPERSTORE
GROUP BY
	CATEGORY,
	SUB_CATEGORY
ORDER BY
	TOTAL_PROFIT ASC;

-- Q4: WHICH MARKET IS DRIVING MORE SALES?
SELECT
	MARKET,
	REGION,
	ROUND(SUM(SALES), 2) AS TOTAL_SALES,
	ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT
FROM
	SUPERSTORE
GROUP BY
	MARKET,
	REGION
ORDER BY
	TOTAL_SALES DESC,
	TOTAL_PROFIT DESC;

-- Q5: TOTAL SALES AND PROFIT PER YEAR (YEARLY TREND)
SELECT
	YEAR,
	ROUND(SUM(SALES), 2) AS TOTAL_SALES,
	ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT
FROM
	SUPERSTORE
GROUP BY
	YEAR
ORDER BY
	YEAR ASC;

-- Q6: WHICH CATEGORY IS KILLING THE PROFIT? + DISCOUNT TRAP
-- Part A: Profit by Category
SELECT
	CATEGORY,
	ROUND(SUM(SALES), 2) AS TOTAL_SALES,
	ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT
FROM
	SUPERSTORE
GROUP BY
	CATEGORY
ORDER BY
	TOTAL_PROFIT ASC;

-- Part B: The Discount Trap - This is what gets you hired
SELECT
	SUB_CATEGORY,
	ROUND(AVG(DISCOUNT), 2) AS AVG_DISCOUNT,
	ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
	COUNT(*) AS TIMES_SOLD
FROM
	SUPERSTORE
GROUP BY
	SUB_CATEGORY
HAVING
	AVG(DISCOUNT) > 0.2
ORDER BY
	TOTAL_PROFIT ASC;

-- Q7: TRANSACTION COUNT BY COUNTRY WITH SEGMENTATION
SELECT
	COUNTRY,
	COUNT(*) AS TOTAL_TRANSACTION_COUNT,
	CASE
		WHEN COUNT(*) >= 1700 THEN 'High Sales'
		WHEN COUNT(*) >= 700 THEN 'Medium Sales'
		WHEN COUNT(*) >= 300 THEN 'Low Sales'
		ELSE 'Very Low Sales'
	END AS SALES_SEGMENT
FROM
	SUPERSTORE
GROUP BY
	COUNTRY
ORDER BY
	TOTAL_TRANSACTION_COUNT DESC;

-- Q8: SHIPPING COST VS PROFIT BY REGION
SELECT
	REGION,
	ROUND(SUM(SHIPPING_COST), 2) AS TOTAL_SHIPPING_COST,
	ROUND(SUM(SALES), 2) AS TOTAL_SALES,
	ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
	ROUND(SUM(PROFIT) * 100.0 / SUM(SALES), 2) AS MARGIN_PCT
FROM
	SUPERSTORE
GROUP BY
	REGION
ORDER BY
	TOTAL_PROFIT ASC;

-- Q9: YEAR-OVER-YEAR PROFIT AND SALES GROWTH (Running Trend)
SELECT
	YEAR,
	ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
	LAG(SUM(PROFIT)) OVER (
		ORDER BY
			YEAR
	) AS PREV_YEAR_PROFIT,
	ROUND(
		SUM(PROFIT) - LAG(SUM(PROFIT)) OVER (
			ORDER BY
				YEAR
		),
		2
	) AS PROFIT_GROWTH_YOY
FROM
	SUPERSTORE
GROUP BY
	YEAR
ORDER BY
	YEAR ASC;

-- Q10: PROFIT AND SALES TREND BY YEAR AND REGION
SELECT
	REGION,
	YEAR,
	ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
	ROUND(SUM(SALES), 2) AS TOTAL_SALES,
	ROUND(
		SUM(PROFIT) - LAG(SUM(PROFIT)) OVER (
			PARTITION BY
				REGION
			ORDER BY
				YEAR ASC
		),
		2
	) AS PROFIT_TREND,
	ROUND(
		SUM(SALES) - LAG(SUM(SALES)) OVER (
			PARTITION BY
				REGION
			ORDER BY
				YEAR ASC
		),
		2
	) AS SALES_TREND
FROM
	SUPERSTORE
GROUP BY
	REGION,
	YEAR
ORDER BY
	REGION,
	YEAR ASC;

